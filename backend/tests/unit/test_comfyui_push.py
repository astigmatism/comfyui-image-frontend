def settings(tmp_path: Path, **overrides: object) -> Settings:
    values: dict[str, object] = {
        "data_dir": tmp_path,
        "session_secret": "test-secret",
        "test_mode": True,
        "comfyui_base_url": "http://comfy.test",
        "comfyui_instance_id": "gpu-primary",
        "comfyui_workflow_directory": "workflows",
    }
    values.update(overrides)
    return Settings(**values)


def instances(tmp_path: Path, **overrides: object) -> ComfyUIInstances:
    return ComfyUIInstances(settings(tmp_path, **overrides))


def test_a_second_image_service_keeps_the_inputs_of_the_images_it_generated(
    tmp_path: Path,
) -> None:
    pool = instances(
        tmp_path,
        comfyui_additional_instances=[
            {
                "id": "gpu-second",
                "label": "Second GPU",
                "base_url": "http://second.test",
            }
        ],
        comfyui_image_worker_ids=["gpu-second"],
    )

    resolved = resolve_target_instance(pool, generating_id="gpu-second")

    assert resolved.id == "gpu-second"
    assert resolve_target_instance(pool, generating_id=None).id == "gpu-primary"


def test_the_prompt_service_is_never_a_home_for_image_inputs(tmp_path: Path) -> None:
    configured = instances(
        tmp_path,
        comfyui_additional_instances=[
            {
                "id": "promptgen",
                "label": "CPU Prompt Service",
                "base_url": "http://prompt.test",
            }
        ],
        comfyui_text_instance_id="promptgen",
    )

    with pytest.raises(AppError) as chosen:
        resolve_target_instance(configured, requested_id="promptgen")
    assert chosen.value.code == "comfyui_input_instance_required"
    assert chosen.value.status_code == 409
    # An image generated by the prompt service still lands on a container that can load it.
    assert resolve_target_instance(configured, generating_id="promptgen").id == "gpu-primary"
    with pytest.raises(AppError) as unknown:
        resolve_target_instance(configured, requested_id="gone")
    assert unknown.value.status_code == 404


class _Record:
    def __init__(self, mime_type: str, source_filename: str, artifact_id: str = "art-1") -> None:
        self.mime_type = mime_type
        self.source_filename = source_filename
        self.artifact_id = artifact_id


def test_an_outbound_name_is_one_loadable_file() -> None:
    assert outbound_filename(_Record("image/png", "moonrise.png")) == "moonrise.png"
    assert outbound_filename(_Record("image/jpeg", "moonrise.png")) == "moonrise.png"
    assert outbound_filename(_Record("image/png", "moonrise")) == "moonrise.png"
    assert outbound_filename(_Record("image/webp", "two  words.png")) == "two words.png"
    assert outbound_filename(_Record("image/png", "../secrets/png")) == "png.png"
    assert outbound_filename(_Record("image/png", "a/b/c.png")) == "c.png"
    assert outbound_filename(_Record("image/png", "....")) == "gallery-art-1.png"
    assert outbound_filename(_Record("image/png", "x" * 300)).startswith("x" * 120)
    assert outbound_filename(_Record("image/png", "keep.png"), override="renamed.png") == (
        "renamed.png"
    )
    assert outbound_filename(_Record("image/jpeg", "keep.png"), override="renamed") == (
        "renamed.jpg"
    )


def _adapter(tmp_path: Path, handler: Any) -> ComfyUIAdapter:
    return ComfyUIAdapter(settings(tmp_path), transport=httpx.MockTransport(handler))


def test_upload_reports_the_reference_comfyui_actually_wrote(tmp_path: Path) -> None:
    seen: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        return httpx.Response(
            200, json={"name": "moonrise_00002.png", "subfolder": "", "type": "input"}
        )

    async def scenario() -> tuple[dict[str, str], str]:
        adapter = _adapter(tmp_path, handler)
        try:
            uploaded = await adapter.upload_input_image(b"bytes", "moonrise.png")
            reference = await adapter.upload_image(b"bytes", "moonrise.png", kind="image")
            return uploaded, reference
        finally:
            await adapter.close()

    uploaded, reference = asyncio.run(scenario())

    assert uploaded == {"name": "moonrise_00002.png", "subfolder": "", "type": "input"}
    assert reference == "moonrise_00002.png"
    body = seen[0].content
    assert b'name="type"' in body and b"input" in body
    assert b'name="overwrite"' in body and b"false" in body
    assert b'filename="moonrise.png"' in body
    assert b"subfolder" not in body.split(b"Content-Disposition")[0]


def test_a_mask_namespace_stays_a_hint_but_a_requested_one_is_asserted(
    tmp_path: Path,
) -> None:
    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(
            200, json={"name": "m.png", "subfolder": "elsewhere", "type": "input"}
        )

    async def scenario() -> tuple[str, str | None]:
        adapter = _adapter(tmp_path, handler)
        try:
            masked = await adapter.upload_image(b"bytes", "m.png", kind="mask")
            namespace_error: str | None = None
            try:
                await adapter.upload_image(b"bytes", "m.png", kind="image", subfolder="chosen")
            except AppError as error:
                namespace_error = error.code
            return masked, namespace_error
        finally:
            await adapter.close()

    masked, namespace_error = asyncio.run(scenario())

    assert masked == "elsewhere/m.png"
    assert namespace_error == "upload_failed"


def test_an_unusable_reference_is_not_reported_as_a_saved_file(tmp_path: Path) -> None:
    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, json={"name": "../escape.png", "type": "input"})

    async def scenario() -> str:
        adapter = _adapter(tmp_path, handler)
        try:
            await adapter.upload_input_image(b"bytes", "moonrise.png")
        except AppError as error:
            return error.code
        finally:
            await adapter.close()
        return "none"

    assert asyncio.run(scenario()) == "upload_failed"


def test_input_choice_lookup_stays_silent_until_the_runtime_is_known(tmp_path: Path) -> None:
    adapter = _adapter(tmp_path, lambda request: httpx.Response(200, json={}))
    try:
        assert adapter.input_lists_file("moonrise.png") is None
        adapter._runtime_object_info = {
            "LoadImage": {"input": {"required": {"image": [["moonrise.png", "sub/other.png"], {}]}}}
        }
        assert adapter.input_lists_file("moonrise.png") is True
        assert adapter.input_lists_file("sub/other.png") is True
        assert adapter.input_lists_file("not-listed.png") is False
    finally:
        asyncio.run(adapter.close())
